// Generates js/pmi-symbol-data.js from PMI's supplied symbol SVGs
// (`PMI branding guidelines/Shapes/*.svg`, kept out of git). Each symbol is one filled path
// on a 300x300 artboard with a 50px margin, so the drawable area is 50..250.
//
// Usage: node scripts/build-pmi-symbols.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'PMI branding guidelines', 'Shapes');

const entries = readdirSync(dir).filter(f => f.toLowerCase().endsWith('.svg')).sort().map(file => {
  const svg = readFileSync(join(dir, file), 'utf8');
  const paths = [...svg.matchAll(/<path\b[^>]*\sd="([^"]+)"[^>]*>/g)].map(m => m[1].replace(/\s+/g, ' ').trim());
  if (!paths.length) throw new Error(`${file}: no <path> found`);
  const evenOdd = /fill-rule="evenodd"/.test(svg);
  const label = file.replace(/\.svg$/i, '');
  const key = label.toLowerCase().replace(/[^a-z0-9]+/g, '-');
  return { key, label, paths, evenOdd };
});

const body = entries.map(e =>
  `  '${e.key}': { label: '${e.label}', evenOdd: ${e.evenOdd}, paths: ${JSON.stringify(e.paths)} }`
).join(',\n');

const out = `// PMI brand symbols — GENERATED by scripts/build-pmi-symbols.mjs from the SVGs PMI supplied in
// \`PMI branding guidelines/Shapes/\`. Do not edit by hand. Each symbol is filled path data on a
// 300x300 artboard whose drawable area is 50..250 (use PMI_SYMBOL_VIEWBOX).
// Rules for using them are in design/PMI-BRAND-EXTRACT.md and enforced by js/pmi-symbols.js.

export const PMI_SYMBOL_VIEWBOX = '50 50 200 200';

export const PMI_SYMBOL_DATA = Object.freeze({
${body}
});
`;
writeFileSync(join(root, 'js', 'pmi-symbol-data.js'), out);
console.log(`Wrote js/pmi-symbol-data.js (${entries.length} symbols: ${entries.map(e => e.key).join(', ')})`);
