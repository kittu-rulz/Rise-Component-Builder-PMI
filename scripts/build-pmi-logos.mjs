// Generates js/pmi-logos.js from PMI's supplied logo SVGs (`PMI branding guidelines/Logo/`, kept
// out of git). Only the RGB, on-screen variants this app places are embedded: the horizontal
// (primary) lockup and the Project Mark, each in full colour (for light surfaces) and white
// (for dark surfaces).
//
// Usage: node scripts/build-pmi-logos.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'PMI branding guidelines', 'Logo');

const SOURCES = {
  horizontalFullColor: 'primarylogo_pmi_horizontal_logo_full_color_rgb.svg',
  horizontalWhite: 'primarylogo_pmi_horizontal_logo_white_rgb.svg',
  markFullColor: 'pmi_logo_pmi_mark_full_color_rgb.svg',
  markWhite: 'pmi_logo_pmi_mark_white_rgb.svg'
};

function readLogo(file) {
  let svg = readFileSync(join(dir, file), 'utf8');
  svg = svg.replace(/<\?xml[^>]*\?>\s*/, '').replace(/\s+/g, ' ').replace(/> </g, '><').trim();
  const box = svg.match(/viewBox="([^"]+)"/);
  if (!box) throw new Error(`${file}: no viewBox`);
  const [, , w, h] = box[1].split(/\s+/).map(Number);
  const inner = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '')
    .replace(/\sid="[^"]*"/g, '')
    .replace(/<defs>.*?<\/defs>/g, '');
  return { viewBox: box[1], aspect: +(w / h).toFixed(4), inner };
}

const logos = Object.fromEntries(Object.entries(SOURCES).map(([key, file]) => [key, readLogo(file)]));

const out = `// PMI logos — GENERATED by scripts/build-pmi-logos.mjs from the SVGs PMI supplied in
// \`PMI branding guidelines/Logo/\`. Do not edit by hand.
//
// PMI logo rules (Visual Identity Guidelines v1.0, "Logos" section), enforced by pmiLogoSvg():
//   - clearspace: half the logo's height (1/2X) on every side — callers keep that space free
//     (see PMI_LOGO_CLEARSPACE_RATIO);
//   - minimum on-screen size: 32px tall (PMI_LOGO_MIN_HEIGHT_PX) — smaller heights are raised;
//   - full colour on light surfaces, white on dark ones; never recoloured, skewed or shadowed.

export const PMI_LOGO_MIN_HEIGHT_PX = 32;
export const PMI_LOGO_CLEARSPACE_RATIO = 0.5;

export const PMI_LOGOS = Object.freeze(${JSON.stringify(logos, null, 2)});
`;
writeFileSync(join(root, 'js', 'pmi-logos.js'), out + `
/**
 * A PMI logo as an inline SVG. \`variant\`: 'horizontal' (primary lockup) or 'mark'; \`tone\`: 'color'
 * (light surfaces) or 'white' (dark surfaces). Height is clamped up to the 32px on-screen minimum.
 * Labelled as an image with the brand name, since it identifies the brand for assistive tech.
 */
export function pmiLogoSvg({ variant = 'horizontal', tone = 'color', height = PMI_LOGO_MIN_HEIGHT_PX, className = 'pmi-logo' } = {}) {
  const key = (variant === 'mark' ? 'mark' : 'horizontal') + (tone === 'white' ? 'White' : 'FullColor');
  const logo = PMI_LOGOS[key];
  const h = Math.max(PMI_LOGO_MIN_HEIGHT_PX, Number(height) || PMI_LOGO_MIN_HEIGHT_PX);
  const w = Math.round(h * logo.aspect);
  return \`<svg class="\${className}" xmlns="http://www.w3.org/2000/svg" viewBox="\${logo.viewBox}" width="\${w}" height="\${h}" role="img" aria-label="PMI">\${logo.inner}</svg>\`;
}
`);
console.log('Wrote js/pmi-logos.js', Object.entries(logos).map(([k, v]) => `${k} ${v.aspect}`).join(', '));
